package io.qrun.platform.identity;

import java.util.List;
import java.util.Map;
import javax.sql.DataSource;
import com.kingsrook.qqq.backend.core.model.session.QSession;
import io.qrun.platform.identity.auth.CrmContactSynchronizer;
import io.qrun.platform.identity.auth.JdbcUserProfileRepository;
import io.qrun.platform.identity.auth.OidcClaims;
import io.qrun.platform.identity.auth.PermissionBundleResolver;
import io.qrun.platform.identity.auth.PlatformAuthCustomizer;
import io.qrun.platform.identity.auth.RolePermissionBundleResolver;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import static org.assertj.core.api.Assertions.assertThat;

class PlatformAuthCustomizerTest
{
   private DataSource dataSource;
   private JdbcTemplate jdbc;

   @BeforeEach
   void setUp()
   {
      JdbcDataSource h2 = new JdbcDataSource();
      h2.setURL("jdbc:h2:mem:identity;MODE=PostgreSQL;DB_CLOSE_DELAY=-1");
      dataSource = h2;
      jdbc = new JdbcTemplate(dataSource);
      jdbc.execute("drop table if exists user_profile");
      jdbc.execute("create table user_profile (id bigint generated by default as identity primary key, oidc_sub varchar(255) not null unique, email varchar(320), display_name varchar(255) not null, created_at timestamp with time zone not null, updated_at timestamp with time zone not null)");
   }

   @Test
   void provisionsFirstLoginAndPopulatesQQQSecurityContext()
   {
      PlatformAuthCustomizer customizer = new PlatformAuthCustomizer(
         new JdbcUserProfileRepository(dataSource),
         roles -> roles.stream().flatMap(role -> ("business-user".equals(role) ? List.of("crm.read", "profile.edit") : List.<String>of()).stream()).toList(),
         CrmContactSynchronizer.NO_OP);
      QSession session = new QSession();

      customizer.customize(session, OidcClaims.from(Map.of(
         "sub", "keycloak-42", "email", "alice@example.com", "preferred_username", "alice",
         "realm_access", Map.of("roles", List.of("business-user")))));

      Long profileId = jdbc.queryForObject("select id from user_profile where oidc_sub = ?", Long.class, "keycloak-42");
      assertThat(session.getIdReference()).isEqualTo("keycloak-42");
      assertThat(session.getSecurityKeyValues(PlatformAuthCustomizer.USER_PROFILE_ID_SECURITY_KEY)).containsExactly(profileId);
      assertThat(session.getPermissions()).containsExactlyInAnyOrder("crm.read", "profile.edit");
      assertThat(session.getValue(PlatformAuthCustomizer.USER_PROFILE_ID_SESSION_VALUE)).isEqualTo(profileId.toString());
   }

   @Test
   void repeatLoginUpdatesMutableClaimsWithoutDuplicatingProfile()
   {
      PlatformAuthCustomizer customizer = new PlatformAuthCustomizer(new JdbcUserProfileRepository(dataSource), PermissionBundleResolver.NONE, CrmContactSynchronizer.NO_OP);
      customizer.customize(new QSession(), OidcClaims.from(Map.of("sub", "same-sub", "email", "old@example.com", "preferred_username", "old")));
      customizer.customize(new QSession(), OidcClaims.from(Map.of("sub", "same-sub", "email", "new@example.com", "preferred_username", "new")));

      assertThat(jdbc.queryForObject("select count(*) from user_profile where oidc_sub = 'same-sub'", Integer.class)).isOne();
      assertThat(jdbc.queryForObject("select email from user_profile where oidc_sub = 'same-sub'", String.class)).isEqualTo("new@example.com");
      assertThat(jdbc.queryForObject("select display_name from user_profile where oidc_sub = 'same-sub'", String.class)).isEqualTo("new");
   }

   @Test
   void synchronizesCrmContactOnlyForBusinessUsers()
   {
      java.util.ArrayList<Long> synced = new java.util.ArrayList<>();
      PlatformAuthCustomizer customizer = new PlatformAuthCustomizer(new JdbcUserProfileRepository(dataSource), PermissionBundleResolver.NONE,
         (profile, claims) -> synced.add(profile.id()));

      customizer.customize(new QSession(), OidcClaims.from(Map.of("sub", "consumer", "preferred_username", "c")));
      customizer.customize(new QSession(), OidcClaims.from(Map.of("sub", "business", "preferred_username", "b", "realm_access", Map.of("roles", List.of("business-user")))));

      assertThat(synced).hasSize(1);
   }

   @Test
   void rejectsTokenWithoutSubject()
   {
      assertThat(org.assertj.core.api.Assertions.catchThrowable(() -> OidcClaims.from(Map.of("email", "a@b.test"))))
         .isInstanceOf(IllegalArgumentException.class).hasMessageContaining("sub");
   }

   @Test
   void bridgesEveryKeycloakRoleToConfiguredPermissionBundle()
   {
      RolePermissionBundleResolver resolver = new RolePermissionBundleResolver(Map.of(
         "platform-admin", List.of("platform.admin", "profile.read"),
         "business-user", List.of("crm.read", "profile.read")));

      assertThat(resolver.resolve(List.of("platform-admin", "business-user", "unknown")))
         .containsExactlyInAnyOrder("platform.admin", "crm.read", "profile.read");
   }
}
